import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import ts from 'typescript';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = resolve(repoRoot, 'packages/wheel/src');
const outputRoot = resolve(repoRoot, 'content/robots/api');

const entries = [
  ['auth', 'wheel/auth', 'auth/index.ts'],
  ['config', 'wheel/config', 'config/index.ts'],
  ['core', 'wheel/core', 'core/index.ts'],
  ['sync', 'wheel/sync', 'sync/index.ts'],
  ['sync-server', 'wheel/sync/server', 'sync/server/index.ts'],
  ['sync-server-cloudflare', 'wheel/sync/server/cloudflare', 'sync/server/cloudflare.ts'],
  ['sync-server-testing', 'wheel/sync/server/testing', 'sync/server/testing.ts'],
  ['kit', 'wheel/kit', 'kit/index.ts'],
  ['router', 'wheel/router', 'router/index.ts'],
  ['debug', 'wheel/debug', 'debug/index.ts'],
  ['testing', 'wheel/testing', 'testing/index.ts'],
  ['testing-playwright', 'wheel/testing/playwright', 'testing/playwright.ts'],
  ['vite', 'wheel/vite', 'vite/index.ts'],
];

const componentAggregate = resolve(sourceRoot, 'components/index.ts');
const componentFamilies = [...readFileSync(componentAggregate, 'utf8').matchAll(/from '\.\/([^']+)'/g)]
  .map((match) => match[1])
  .filter((family, index, all) => all.indexOf(family) === index);

const allSourceFiles = [
  ...entries.map(([, , path]) => resolve(sourceRoot, path)),
  componentAggregate,
  ...componentFamilies.map((family) => resolve(sourceRoot, `components/${family}/index.ts`)),
];

const program = ts.createProgram(allSourceFiles, {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  jsx: ts.JsxEmit.Preserve,
  skipLibCheck: true,
});
const checker = program.getTypeChecker();

function exportedSymbols(sourcePath) {
  const source = program.getSourceFile(sourcePath);
  if (!source) throw new Error(`TypeScript did not load ${sourcePath}`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  if (!moduleSymbol) throw new Error(`TypeScript did not resolve ${sourcePath}`);
  return checker.getExportsOfModule(moduleSymbol).sort((a, b) => a.name.localeCompare(b.name));
}

function targetOf(symbol) {
  return symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
}

function declarationOf(symbol) {
  const target = targetOf(symbol);
  return target.valueDeclaration ?? target.declarations?.[0] ?? symbol.declarations?.[0];
}

function kindOf(symbol) {
  const target = targetOf(symbol);
  const flags = target.flags;
  if (flags & ts.SymbolFlags.Class) return 'class';
  if (flags & ts.SymbolFlags.Function) return 'function';
  if (flags & ts.SymbolFlags.Interface) return 'interface';
  if (flags & ts.SymbolFlags.TypeAlias) return 'type';
  if (flags & ts.SymbolFlags.Enum) return 'enum';
  if (flags & ts.SymbolFlags.NamespaceModule) return 'namespace';
  if (flags & ts.SymbolFlags.Variable) return 'value';
  return 'export';
}

function descriptionOf(symbol) {
  const target = targetOf(symbol);
  const parts = target.getDocumentationComment(checker);
  const fallback = parts.length === 0 ? symbol.getDocumentationComment(checker) : parts;
  const text = ts.displayPartsToString(fallback).replace(/\s+/g, ' ').trim();
  return text || 'Public export. Read the linked declaration for its complete contract.';
}

function sourceLink(symbol) {
  const declaration = declarationOf(symbol);
  if (!declaration) return 'source declaration unavailable';
  const source = declaration.getSourceFile();
  const line = source.getLineAndCharacterOfPosition(declaration.getStart(source)).line + 1;
  const path = relative(repoRoot, source.fileName).replaceAll('\\', '/');
  return `[${path}:${line}](../../../${path}#L${line})`;
}

function renderSymbols(sourcePath) {
  const symbols = exportedSymbols(sourcePath);
  return symbols.map((symbol) => [
    `## \`${symbol.name}\``,
    '',
    `Kind: ${kindOf(symbol)}. Source: ${sourceLink(symbol)}.`,
    '',
    descriptionOf(symbol),
    '',
  ].join('\n')).join('\n');
}

function renderEntry(specifier, sourcePath) {
  const repoPath = relative(repoRoot, sourcePath).replaceAll('\\', '/');
  return `# \`${specifier}\` API

> Generated from [\`${repoPath}\`](../../../${repoPath}). Do not edit this file by hand.

Import only from \`${specifier}\`. The linked declarations are the source of truth for signatures, members, defaults, and limits.

${renderSymbols(sourcePath)}`;
}

function renderComponents() {
  const groups = [
    `# \`wheel/components\` API

> Generated from the aggregate and deep component entry files. Do not edit this file by hand.

Import the aggregate API from \`wheel/components\`. Import one family from \`wheel/components/<family>\`. Load \`wheel/components/styles\` once when you want the default theme.

## Aggregate entry

${renderSymbols(componentAggregate)}`,
  ];
  for (const family of componentFamilies) {
    const sourcePath = resolve(sourceRoot, `components/${family}/index.ts`);
    groups.push(`## \`wheel/components/${family}\`

${renderSymbols(sourcePath).replaceAll(/^## /gm, '### ')}`);
  }
  return groups.join('\n\n');
}

export function buildRobotApiDocuments() {
  const documents = new Map();
  for (const [slug, specifier, path] of entries) {
    documents.set(`${slug}.md`, renderEntry(specifier, resolve(sourceRoot, path)));
  }
  documents.set('components.md', renderComponents());
  return documents;
}

function documentSource(content) {
  return `${content.trimEnd()}\n`;
}

export function checkRobotApiDocuments() {
  const stale = [];
  for (const [name, content] of buildRobotApiDocuments()) {
    const path = resolve(outputRoot, name);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== documentSource(content)) stale.push(name);
  }
  return stale;
}

function writeRobotApiDocuments() {
  mkdirSync(outputRoot, { recursive: true });
  for (const [name, content] of buildRobotApiDocuments()) {
    writeFileSync(resolve(outputRoot, name), documentSource(content));
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = checkRobotApiDocuments();
    if (stale.length > 0) {
      throw new Error(`Robot API docs are stale: ${stale.join(', ')}. Run bun run docs:robots.`);
    }
    console.log('Robot API docs match the public source entries.');
  } else {
    writeRobotApiDocuments();
    console.log(`Wrote ${buildRobotApiDocuments().size} robot API documents.`);
  }
}
