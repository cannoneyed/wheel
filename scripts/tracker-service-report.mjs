import {
  readFileSync,
  readdirSync,
  writeFileSync
} from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const servicesDirectory = resolve(root, 'packages/tracker/src/services');
const outputPath = resolve(root, 'packages/tracker/SERVICE-REPORT.md');

const rows = readdirSync(servicesDirectory)
  .filter((filename) => filename.endsWith('.ts'))
  .flatMap((filename) => {
    const source = readFileSync(
      resolve(servicesDirectory, filename),
      'utf8'
    );
    const className = source.match(
      /export class (\w+) extends (?:Live|Layout)?Service/
    )?.[1];
    if (!className) {
      return [];
    }
    return [
      {
        className,
        filename,
        lines: source.trimEnd().split('\n').length,
        dependencies: [...source.matchAll(/this\.service\(/g)].length
      }
    ];
  })
  .sort(
    (left, right) =>
      right.dependencies - left.dependencies ||
      right.lines - left.lines ||
      left.className.localeCompare(right.className)
  );

const generated = `# Tracker service shape

Generated by \`bun run report:tracker-services\`. Direct dependencies count calls to \`this.service(...)\`; lines are a visibility signal, not a pass/fail limit.

| Service | File | Direct services | Lines |
|---|---|---:|---:|
${rows
  .map(
    (row) =>
      `| ${row.className} | \`${row.filename}\` | ${row.dependencies} | ${row.lines} |`
  )
  .join('\n')}
`;

if (process.argv.includes('--write')) {
  writeFileSync(outputPath, generated);
  process.stdout.write(`updated ${outputPath}\n`);
} else {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== generated) {
    process.stderr.write(
      'Tracker service report is stale. Run `bun run report:tracker-services`.\n'
    );
    process.exitCode = 1;
  }
}
